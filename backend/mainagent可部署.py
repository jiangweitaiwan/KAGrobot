def register_tool(tool_name: str):
    """裝飾器：將函式註冊為某個 tool name 的實作。

    tool_name 須與 TOOLS_REGISTRY 中的 key 一致。

    Usage::

        @register_tool("growth_select")
        def my_growth_screener(stock_symbol: str) -> str:
            ...
    """
    def _decorator(func: Callable[..., str]) -> Callable[..., str]:
        _TOOL_IMPLEMENTATIONS[tool_name] = func
        return func
    return _decorator


