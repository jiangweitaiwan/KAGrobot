class SocratesChatBot:
    """單一 LLM + 自訂 tool_executor_node 的蘇格拉底對話 Agent。

    Graph 流程：
        agent ──(tool_calls)──► tool_executor ──► agent
        agent ──(no calls)───► END

    ``tool_executor_node`` 同時負責：
      - 執行 retrieve_concepts 取得完整資料
      - 將 candidates / chains_raw 直接存入 ``_InternalState``（不塞進 ToolMessage）
      - 只將精簡 display 放入 ToolMessage，減少 agent 收到的 token 數

    因此 messages 欄位使用標準 ``add_messages``，不需要 filter_node 或自訂 reducer。

    對外 API 與原版完全相容：
        state = bot.init_state()
        state = bot.process_message(state, user_input)
        reply = bot.get_last_reply(state)
    """

    def __init__(
            self,
            retriever: Neo4jReasoningRetriever,
            *,
            model:            str  = "gemini-2.5-flash", # 預設改為 Gemini 2.5 Flash
            api_key:          str  = "",
            concept_to_agent: Optional[Dict[str, AgentType]] = None,
            top_k_entities:   int  = 3,
        ):
            self._retriever        = retriever
            self._concept_to_agent = concept_to_agent or CONCEPT_TO_AGENT
            self._top_k            = top_k_entities

            if not api_key:
                api_key = get_settings().google_api_key

            # ── 修改處：改用 ChatGoogleGenerativeAI ──
            base_llm = ChatGoogleGenerativeAI(
                model=model,
                google_api_key=api_key,
                temperature=0.1,
                # 不在此處傳 system_instruction 以避免某些版本的警告
                # 讓 agent_node 中的 SystemMessage 自動轉換
            )

            #llm_with_system = base_llm.bind(system_instruction=_SYSTEM_PROMPT)

            self._retrieve_tool  = self._make_retrieve_tool()
            # Gemini 支援 bind_tools，會自動處理 StructuredTool 轉換
            self._llm_with_tools = base_llm.bind_tools([self._retrieve_tool])
            self._graph          = self._build_graph()




