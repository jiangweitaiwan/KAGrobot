        """回傳 Agent 的摘要資訊（適合 debug / logging）。"""
        lines = [
            f"MainAgent 摘要",
            f"  需求: {self.socrates_query}",
            f"  工具: {', '.join(self.tool_names)}",
            f"  對話輪次: {sum(1 for m in self._history if isinstance(m, HumanMessage))}",
        ]
        return "\n".join(lines)