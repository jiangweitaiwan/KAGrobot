    # Public API
    # ------------------------------------------------------------------

    @staticmethod
    def init_state() -> ChatState:
        return ChatState(
            messages         = [],
            agent_messages   = [],
            phase            = ConversationPhase.RUNNING.value,
            query            = None,
            reasoning_chains = None,
            candidates       = None,
            selected_index   = None,
            tools            = None,
            parameters       = None,
        )

    def process_message(self, state: ChatState, user_input: str) -> ChatState:
        """處理一輪使用者輸入，回傳更新後的 ChatState。

        流程：
        ┌──────────────────────────────────────────────────────────────┐
        │  1. user_input → state["messages"]                           │
        │  2. LangGraph ReAct loop                                     │
        │     agent ──(tool_calls)──► tool_executor ──► agent          │
        │     agent ──(no calls)───► END                               │
        │     tool_executor: 存 candidates/chains_raw 至 _InternalState│
        │                    只把精簡 display 放入 ToolMessage          │
        │  3. 從 graph_result 讀取 tool_executor 存入的欄位            │
        │     同步 candidates / chains_raw / query → ChatState / cache │
        │  4. 從最後一則 AIMessage 解析 JSON                           │
        │     action="ask"      → 更新對話歷史，繼續                   │
        │     action="resolved" → _handle_resolved() → 填 tools/params │
        └──────────────────────────────────────────────────────────────┘
        """
        if state.get("phase") == ConversationPhase.RESOLVED.value:
            return state

        state["messages"].append(HumanMessage(content=user_input))

        # # ── session cache（供 _handle_resolved 使用）──
        # sid   = id(state)
        # cache = self._session_cache.setdefault(sid, {"candidates": [], "chains_raw": []})
        # if state.get("candidates") and not cache.get("candidates"):
        #     cache["candidates"] = state["candidates"]
        # if state.get("reasoning_chains") and not cache.get("chains_raw"):
        #     cache["chains_raw"] = state["reasoning_chains"]

        # ── Step 2：ReAct loop ──
        prior = state.get("agent_messages") or []

        # 避免多輪對話時重複注入 system prompt：
        # - graph_result["messages"] 會包含本輪輸入的完整 messages（通常也包含 SystemMessage）
        # - 若下一輪又在最前面加一次 SystemMessage，system prompt 會不斷累積
        normalized_prior: List[BaseMessage] = []
        first_system: Optional[SystemMessage] = None
        for m in prior:
            if isinstance(m, SystemMessage):
                if first_system is None:
                    first_system = m
                # 其他 SystemMessage（包含重複注入）一律略過
                continue
            normalized_prior.append(m)

        system_msg = first_system or SystemMessage(content=_SYSTEM_PROMPT)

        graph_result = self._graph.invoke({
            "messages":   [system_msg] + normalized_prior + [HumanMessage(content=user_input)],
            "candidates": state.get("candidates") or [],
            "chains_raw": state.get("chains_raw") or [],
            "query":      state.get("query"),
        })
        new_agent_msgs: List[BaseMessage] = graph_result["messages"]
        state["agent_messages"] = new_agent_msgs

        # ── Step 3：從 graph_result 同步 tool_executor 存入的欄位 ──
        if graph_result.get("query"):
            state["query"] = graph_result["query"]
        if graph_result.get("candidates"):
            state["candidates"] = graph_result["candidates"]
            # cache["candidates"] = graph_result["candidates"]
        if graph_result.get("chains_raw"):
            state["reasoning_chains"] = graph_result["chains_raw"]
            # cache["chains_raw"]       = graph_result["chains_raw"]

        # ── Step 4：從最後一則 AIMessage 解析 JSON ──
        bot_resp = self._parse_bot_response(new_agent_msgs)
        ai_text  = bot_resp.get("ai_message", "")
        action   = bot_resp.get("action", "ask")

        state["messages"].append(AIMessage(content=ai_text))

        if action == "resolved":
            self._handle_resolved(state, user_input, bot_resp)
        return state

    def get_last_reply(self, state: ChatState) -> str:
        for msg in reversed(state.get("messages", [])):
            if isinstance(msg, AIMessage):
                return msg.content
        return ""

    # ------------------------------------------------------------------
    # LangGraph Graph
    # ------------------------------------------------------------------

    def _build_graph(self):
        """
        agent ──(tool_calls)──► tool_executor ──► agent
        agent ──(no calls)───► END

        messages 使用標準 add_messages（append）。
        tool_executor 直接將 candidates / chains_raw 存入 state 欄位，
        ToolMessage 只包含精簡 display，不含大型 JSON。
        """
        llm      = self._llm_with_tools
        tool_map = {self._retrieve_tool.name: self._retrieve_tool}

        def agent_node(state: _InternalState) -> dict:
            msgs     = state["messages"]
            response = llm.invoke(msgs)
            return {"messages": [response]}

        def tool_executor_node(state: _InternalState) -> dict:
            """執行 tool_calls。

            retrieve_concepts 回傳的完整 JSON 在此拆解：
              - candidates / chains_raw / query → 存入 state 欄位（不進 LLM context）
              - display                         → 放入 ToolMessage（LLM 只看這個）
            其他未知 tool 的結果原樣放入 ToolMessage。
            """
            last          = state["messages"][-1]
            tool_messages: List[ToolMessage] = []
            state_updates: dict = {}

            for tc in getattr(last, "tool_calls", []):
                tool = tool_map.get(tc["name"])
                if tool is None:
                    tool_messages.append(ToolMessage(
                        content=f"Unknown tool: {tc['name']}",
                        tool_call_id=tc["id"],
                        name=tc["name"],
                    ))
                    continue

                raw_result = tool.invoke(tc["args"])

                # retrieve_concepts：拆解完整結果，只傳 display 給 LLM
                try:
                    data = json.loads(raw_result)
                except (json.JSONDecodeError, TypeError):
                    data = {}

                if data.get("found"):
                    # 存入 state 欄位（process_message 從 graph_result 讀取）
                    state_updates["candidates"] = data.get("candidates", [])
                    state_updates["chains_raw"] = data.get("chains_raw", [])
                    state_updates["query"]      = data.get("query", "")
                    # 只把精簡 display 給 LLM
                    slim = data.get("display") or "（查無結果）"
                else:
                    # found=False 或解析失敗：把 message 或原始內容給 LLM
                    slim = data.get("message") or raw_result

                tool_messages.append(ToolMessage(
                    content=slim,
                    tool_call_id=tc["id"],
                    name=tc["name"],
                ))

            return {"messages": tool_messages, **state_updates}

        def route(state: _InternalState) -> str:
            last = state["messages"][-1]
            if isinstance(last, AIMessage) and getattr(last, "tool_calls", None):
                return "tool_executor"
            return END

        g = StateGraph(_InternalState)
        g.add_node("agent",         agent_node)
        g.add_node("tool_executor", tool_executor_node)
        g.set_entry_point("agent")
        g.add_conditional_edges("agent", route, {"tool_executor": "tool_executor", END: END})
        g.add_edge("tool_executor", "agent")
        return g.compile()

    # ------------------------------------------------------------------
    # retrieve_concepts Tool
    # ------------------------------------------------------------------

    def _make_retrieve_tool(self) -> StructuredTool:
        retriever        = self._retriever
        top_k            = self._top_k
        concept_to_agent = self._concept_to_agent

        def retrieve_concepts(query: str) -> str:
            """查詢知識圖譜，找出與使用者需求最相關的 Resulting Concept 清單。

            Args:
                query: 精確的英文查詢語句，捕捉使用者核心意圖。

            Returns:
                JSON 字串，由 tool_executor_node 負責拆解：
                  found      (bool)  — 是否找到結果
                  display    (str)   — 精簡候選清單（LLM 只收到這個）
                  candidates (list)  — 結構化候選資料（存入 state，不進 LLM）
                  chains_raw (list)  — 完整推理鏈（存入 state，不進 LLM）
                  query      (str)   — 實際查詢語句
            """
            chains: List[ReasoningChain] = retriever.retrieve(
                query, top_k_entities=top_k
            )

            if not chains:
                return json.dumps({
                    "found":      False,
                    "message":    "No relevant concepts found in the knowledge graph.",
                    "candidates": [],
                    "chains_raw": [],
                    "display":    "",
                    "query":      query,
                }, ensure_ascii=False)

            chains_raw = [_serialize_chain(c) for c in chains]
            candidates = _build_candidates_from_chains(chains, concept_to_agent)

            # display：每筆一行，只顯示編號 / 模型概念 / 工具名稱 / 工具描述
            lines: List[str] = []
            for c in candidates:
                tool_name = c.get("primary_tool") or "（尚未對應）"
                tool_desc = TOOLS_REGISTRY.get(tool_name, {}).get("description", "")
                desc_part = f" — {tool_desc}" if tool_desc else ""
                lines.append(
                    f"[{c['index']}] {c['rc_name'] or '（未命名）'}"
                    f"｜工具：{tool_name}{desc_part}"
                )

            return json.dumps({
                "found":      True,
                "query":      query,
                "candidates": candidates,
                "chains_raw": chains_raw,
                "display":    "\n".join(lines),
            }, ensure_ascii=False)

        return StructuredTool.from_function(
            func=retrieve_concepts,
            name="retrieve_concepts",
            description=(
                "查詢知識圖譜，找出與使用者需求最相關的 Resulting Concept 清單。"
                "需求釐清完成後呼叫此 tool，傳入精確的英文查詢語句。"
            ),
        )

    # ------------------------------------------------------------------
    # JSON 解析：從最後一則 AIMessage 取出 action / ai_message
    # ------------------------------------------------------------------


    @staticmethod
    def _extract_raw_content(msgs: List[BaseMessage]) -> str:
        """從 agent_messages 中找最後一則有 content 的 AIMessage，回傳原始文字。

        相容兩種 Gemini 回傳格式：
            - content 為 list[dict]：text 在 content[0]['text']
            - content 為 str：直接回傳
        任何情況下找不到內容皆 raise。
        """
        for msg in reversed(msgs):
            if not (isinstance(msg, AIMessage) and msg.content):
                continue 
            if isinstance(msg.content, list):
                if not msg.content:
                    raise ValueError("AIMessage content list is empty.")
                item = msg.content[0]
                if isinstance(item, dict):
                    raw = item.get('text', '')
                else:
                    raw = str(item)
            else:
                raw = str(msg.content)
            raw = raw.strip()
            if not raw:
                raise ValueError("AIMessage content is blank.")
            return raw
        raise ValueError("No AIMessage with content found in agent_messages.")



    @staticmethod
    def _parse_bot_response(msgs: List[BaseMessage]) -> dict:
        """從 agent_messages 中找最後一則有 content 的 AIMessage，解析 JSON。
 
        LLM 被 system prompt 要求輸出：
            {"action": "ask"|"resolved", "ai_message": "...", "selected_index": null|int}
 
        若解析失敗（LLM 沒遵守格式），回傳預設值讓對話繼續。
        """
        raw = SocratesChatBot._extract_raw_content(msgs)
 
        # 容錯：去除可能的 markdown code block 包裝
        if raw.startswith("```"):
            raw = raw.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
 
        try:
            data = json.loads(raw)
            if "action" in data and "ai_message" in data:
                return data
        except (json.JSONDecodeError, TypeError):
            pass
 
        # 解析失敗：把原始內容當作 ai_message，action 維持 ask
        return {"action": "ask", "ai_message": raw, "selected_index": None}

    # ------------------------------------------------------------------
    # 處理 resolved
    # ------------------------------------------------------------------

    def _handle_resolved(
        self,
        state:      ChatState,
        user_input: str,
        bot_resp:   dict,
    ) -> None:
        """
        LLM 輸出 action="resolved" 後，由 process_message 呼叫此方法。
 
        解析策略（兩層 fallback）：
        1. 優先使用 LLM 在 bot_resp["selected_index"] 中回填的 1-based 編號。
           這是主要路徑，因為 LLM 在決定 resolved 的當下已掌握完整上下文。
        2. 若 LLM 未填或填入無效值，退回舊的 _parse_selection 規則式解析。
        3. 兩者均失敗（LLM 誤判為 resolved），靜默維持 RUNNING，讓下一輪追問。
        """
        candidates = state.get("candidates") or []
        chains_raw = state.get("reasoning_chains") or []
 
        if not candidates:
            return
 
        chosen_idx: Optional[int] = None
 
        # ── 層 1：使用 LLM 提供的 selected_index（1-based → 轉成 0-based）──
        llm_index = bot_resp.get("selected_index")
        if isinstance(llm_index, (int, float)) and llm_index is not None:
            llm_index = int(llm_index)
            if 1 <= llm_index <= len(candidates):
                chosen_idx = llm_index - 1
 
        # ── 層 2：Fallback — 規則式解析 user_input ──
        if chosen_idx is None:
            chosen_idx = _parse_selection(user_input, candidates)
 
        # ── 層 3：兩者皆失敗 → LLM 誤判，靜默維持 RUNNING ──
        if chosen_idx is None:
            return
 
        chosen        = candidates[chosen_idx]
        tools, params = _resolve_tools_from_candidate(
            chosen, chains_raw, self._concept_to_agent
        )
 
        state["selected_index"] = chosen_idx
        state["tools"]          = tools
        state["parameters"]     = params
        state["phase"]          = ConversationPhase.RESOLVED.value

    # ------------------------------------------------------------------
    # CLI 互動模式
    # ------------------------------------------------------------------

    def run_interactive(self) -> ChatState:
        state = self.init_state()
        print("=== SocratesChatBot ===\n")

        # 觸發開場白
        state = self.process_message(state, "你好，請開始引導我。")
        print(f"Bot: {self.get_last_reply(state)}\n")

        while state.get("phase") != ConversationPhase.RESOLVED.value:
            try:
                user_input = input("You: ").strip()
            except (EOFError, KeyboardInterrupt):
                print("\n[中斷]")
                break
            if not user_input:
                continue

            state = self.process_message(state, user_input)
            print(f"Bot: {self.get_last_reply(state)}\n")

        print("=== 最終結果 ===")
        print(json.dumps({
            "query":            state.get("query"),
            "selected_index":   state.get("selected_index"),
            "tools":            state.get("tools"),
            "parameters":       state.get("parameters"),
            "reasoning_chains": state.get("reasoning_chains"),
        }, ensure_ascii=False, indent=2))
        return state

