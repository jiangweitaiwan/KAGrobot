class MainAgent:
    """無狀態設計的 MainAgent (Gemini 2.5 Flash)"""

    def __init__(
        self,
        *,
        model: str = "gemini-2.5-flash",
        api_key: str = "",
    ):
        if not api_key:
            api_key = get_settings().google_api_key
        # 1. 初始化全域共用的基礎設施（移除了所有與使用者相關的狀態）
        self._model_name = model
        self._api_key = api_key

        # 建立一個乾淨、未綁定任何工具的基礎 LLM 實例
        self._base_llm = ChatGoogleGenerativeAI(
            model=model,
            google_api_key=api_key,
            temperature=0
            
        )

    def chat(
        self,
        user_input: str,
        socrates_state: ChatState,
        history: List[BaseMessage]
    ) -> dict:
        """單次處理對話請求（完全無狀態）。

        Args:
            user_input: 使用者當次輸入的文字。
            socrates_state: 包含了 query, tools, parameters 等意圖收斂結果。
            history: 目前為止的對話歷史紀錄（由外部傳入）。

        Returns:
            dict: 包含助理回應、工具呼叫紀錄、以及更新後的完整歷史。
        """
        # 1. 驗證階段
        if socrates_state.get("phase") != ConversationPhase.RESOLVED.value:
            raise ValueError(
                f"MainAgent 需要 phase='resolved'。目前為 {socrates_state.get('phase')}"
            )

        # 2. 動態生成本次請求專屬的 Prompt 與 Tools
        system_prompt = build_system_prompt(socrates_state)
        tools = build_tools_from_state(socrates_state)
        has_tools = bool(tools)

        # 3. 動態配置 LLM (透過 with_config 注入 system instruction，並綁定工具)
        # llm_configured = self._base_llm.with_config(
        #     config={"system_instruction": system_prompt}
        # )
        llm_bound = self._base_llm.bind_tools(tools) if has_tools else llm_configured

        # 4. 即時組裝 LangGraph (在 Python 中組裝圖表極快，微秒級別)
        def call_model(state: AgentState) -> AgentState:
            # 避免在多輪/工具回合中，history 裡若意外包含 SystemMessage
            # 造成 system prompt 疊加；本次一律只注入一份當輪動態 system_prompt。
            normalized_messages: List[BaseMessage] = [
                m for m in state["messages"] if not isinstance(m, SystemMessage)
            ]
            response = llm_bound.invoke(
                [SystemMessage(content=system_prompt)] + normalized_messages
            )
            return {"messages": [response]}

        def should_continue(state: AgentState) -> str:
            last = state["messages"][-1]
            if hasattr(last, "tool_calls") and last.tool_calls:
                return "tools"
            return END

        graph_builder = StateGraph(AgentState)
        graph_builder.add_node("agent", call_model)

        if has_tools:
            graph_builder.add_node("tools", ToolNode(tools))
            graph_builder.set_entry_point("agent")
            graph_builder.add_conditional_edges(
                "agent", should_continue, {"tools": "tools", END: END}
            )
            graph_builder.add_edge("tools", "agent")
        else:
            graph_builder.set_entry_point("agent")
            graph_builder.add_edge("agent", END)

        graph = graph_builder.compile()

        # 5. 準備執行狀態（不污染傳入的原始 history，複製一份）
        current_messages = list(history)
        current_messages.append(HumanMessage(content=user_input))

        # 6. 執行 Graph
        result = graph.invoke({"messages": current_messages})

        # 7. 整理並解析回傳結果
        updated_messages = list(result["messages"])
        content = SocratesChatBot._extract_raw_content(updated_messages)
        # last_msg = updated_messages[-1]
        # content = last_msg.content if hasattr(last_msg, "content") else str(last_msg)

        # 找出「本次對話」中新增的工具呼叫
        tool_calls_made: List[str] = []
        new_messages = updated_messages[len(history):]
        for msg in new_messages:
            if hasattr(msg, "tool_calls") and msg.tool_calls:
                tool_calls_made.extend(tc["name"] for tc in msg.tool_calls)

        return {
            "content": content,
            "tool_calls_made": tool_calls_made,
            "messages": updated_messages, # 後端需將這個存回 Redis 或資料庫
        }

    # ── 工具函式（可選） ──

    def describe(self, socrates_state: ChatState) -> str:
        """回傳 Agent 的摘要資訊（改為傳入 state 才能讀取）。"""
        query = socrates_state.get("query")
        tools = build_tools_from_state(socrates_state)
        tool_names = [t.name for t in tools]

        lines = [
            f"MainAgent 摘要 (Stateless)",
            f"  當前需求: {query}",
            f"  動態工具: {', '.join(tool_names)}",
        ]
        return "\n".join(lines)


    # ── 狀態查詢 ──

    @property
    def system_prompt(self) -> str:
        return self._system_prompt

    @property
    def tools(self) -> List[StructuredTool]:
        return list(self._tools)

    @property
    def tool_names(self) -> List[str]:
        return [t.name for t in self._tools]

    @property
    def socrates_query(self) -> Optional[str]:
        return self._socrates_state.get("query")

