"""#SBERT ONNX Encoder (本地 embedding)"""

# ============================================================
# SBERT ONNX Encoder (本地 embedding)
# ============================================================

class SbertOnnxEncoder:
    def __init__(self, model_path: str, tokenizer_dir: str):
        opts = ort.SessionOptions()
        opts.enable_mem_pattern = False   # 關閉 buffer 重用，解決 shape mismatch
        opts.enable_cpu_mem_arena = False  # 加這行
        self.session = ort.InferenceSession(
            model_path,
            sess_options=opts,
            providers=["CPUExecutionProvider"]
        )
        self.tokenizer = AutoTokenizer.from_pretrained(tokenizer_dir)


    def tokenize(self, text: str, max_length: int = 256):
        encoded = self.tokenizer(
            text,
            max_length=max_length,
            padding="max_length",
            truncation=True,
            return_tensors="np"
        )
        return encoded["input_ids"], encoded["attention_mask"]

    def mean_pooling(self, token_embeddings: np.ndarray, attention_mask: np.ndarray) -> np.ndarray:
        mask = attention_mask[..., None].astype(np.float32)
        sum_mask = mask.sum(axis=1)
        sum_mask = np.clip(sum_mask, a_min=1e-9, a_max=None)
        return (token_embeddings * mask).sum(axis=1) / sum_mask

    def encode(self, sentences: Union[str, List[str]], normalize: bool = True) -> np.ndarray:
        if isinstance(sentences, str):
            sentences = [sentences]

        input_ids_list, attention_mask_list = [], []
        for s in sentences:
            ids, mask = self.tokenize(s)
            input_ids_list.append(ids)
            attention_mask_list.append(mask)

        input_ids = np.vstack(input_ids_list).astype(np.int64)
        attention_mask = np.vstack(attention_mask_list).astype(np.int64)

        outputs = self.session.run(None, {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
        })

        embeddings = self.mean_pooling(outputs[0], attention_mask)

        if normalize:
            norms = np.linalg.norm(embeddings, axis=1, keepdims=True)
            norms = np.clip(norms, a_min=1e-9, a_max=None)
            embeddings = embeddings / norms

        return embeddings

