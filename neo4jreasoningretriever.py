# ============================================================
# Neo4jReasoningRetriever
#   - Embedding 匹配：本地（name + description，merged 展開）
#   - 圖搜尋 (traversal)：雲端 Neo4j Cypher
# ============================================================

class Neo4jReasoningRetriever:

    def __init__(self, uri: str, password: str,
                 model_path: str, tokenizer_dir: str):
        self.driver = GraphDatabase.driver(uri, auth=("neo4j", password))
        self.encoder = SbertOnnxEncoder(model_path, tokenizer_dir)
        self._embedding_index: List[Dict[str, Any]] = []
        self._embeddings_loaded = False

    def close(self):
        self.driver.close()

    # ----------------------------------------------------------
    # Embedding 載入：從 Neo4j 讀取 Concept，展開 merged，本地編碼
    # ----------------------------------------------------------

    def load_embeddings(self):
        """公開方法，可隨時重新載入 embedding index。"""
        self._load_concept_embeddings()

    def _load_concept_embeddings(self):
        with self.driver.session() as session:
            rows = session.run(
                """
                MATCH (c:Concept)
                RETURN elementId(c)      AS eid,
                       c.name            AS name,
                       c.type            AS type,
                       c.description     AS description,
                       c.merged_names        AS merged_names,
                       c.merged_descriptions AS merged_descriptions
                """
            ).data()

        variants: List[Dict[str, Any]] = []
        for row in rows:
            eid       = row["eid"]
            node_name = row["name"]
            node_type = row["type"]
            m_names   = row["merged_names"]
            m_descs   = row["merged_descriptions"]

            if m_names and len(m_names) > 0:
                # merged concept → 拆成多個 variant
                for i, mn in enumerate(m_names):
                    md = m_descs[i] if (m_descs and i < len(m_descs)) else ""
                    variants.append({
                        "element_id": eid,
                        "node_name": node_name,
                        "node_type": node_type,
                        "variant_name": mn,
                        "variant_description": md or "",
                    })
            else:
                variants.append({
                    "element_id": eid,
                    "node_name": node_name,
                    "node_type": node_type,
                    "variant_name": node_name or "",
                    "variant_description": row["description"] or "",
                })

        # 分批編碼（避免記憶體不足）
        BATCH = 64
        texts = [f"{v['variant_name']} {v['variant_description']}" for v in variants]
        all_embs: List[np.ndarray] = []
        for i in range(0, len(texts), BATCH):
            all_embs.append(self.encoder.encode(texts[i:i + BATCH]))


            # batch = texts[i:i + BATCH]
            # original_len = len(batch)

            # # 若不足 BATCH，用空字串 pad 到 BATCH 大小
            # if original_len < BATCH:
            #     batch = batch + [".."] * (BATCH - original_len)

            # embs = self.encoder.encode(batch)   # shape: (BATCH, d)

            # # 只取原本的部分，丟掉 padding
            # all_embs.append(embs[:original_len])






        if all_embs:
            emb_matrix = np.vstack(all_embs)          # (N, d)
            for idx, v in enumerate(variants):
                v["embedding"] = emb_matrix[idx]

        self._embedding_index = variants
        self._embeddings_loaded = True
        print(f"Loaded {len(variants)} concept variants from {len(rows)} concept nodes.")

    # ----------------------------------------------------------
    # Entity Matching：本地 embedding cosine similarity
    # ----------------------------------------------------------

    def _match_entities(self, query: str, top_k: int = 3) -> List[Dict[str, Any]]:
        """
        回傳 top-k 相似的 concept variant。
        每筆包含: element_id, node_name, node_type,
                  matched_name, matched_description, score
        同一個 Concept 節點的不同 variant 不去重。
        """
        if not self._embeddings_loaded:
            self._load_concept_embeddings()

        query_emb = self.encoder.encode(query)[0]       # (d,) 已正規化

        scored: List[Dict[str, Any]] = []
        for v in self._embedding_index:
            if "embedding" not in v:
                continue
            score = float(np.dot(query_emb, v["embedding"]))
            scored.append({
                "element_id": v["element_id"],
                "node_name": v["node_name"],
                "node_type": v["node_type"],
                "matched_name": v["variant_name"],
                "matched_description": v["variant_description"],
                "score": score,
            })

        scored.sort(key=lambda x: x["score"], reverse=True)
        return scored[:top_k]

    # ----------------------------------------------------------
    # 對外主介面
    # ----------------------------------------------------------

    def retrieve(self, query: str, top_k_entities: int = 3) -> List[ReasoningChain]:
        """
        1. 本地 embedding 找 top-k 起點 concept
        2. 依 element_id 去重（取最高分 variant）以避免重複 traversal
        3. 依 concept kind 走雲端 Neo4j 取推理鏈
        """
        matches = self._match_entities(query, top_k=top_k_entities)
        if not matches:
            return []

        # 依 element_id 去重，保留最高分的 variant（避免同節點重複 traversal）
        seen: Dict[str, Dict[str, Any]] = {}
        for m in matches:
            eid = m["element_id"]
            if eid not in seen or m["score"] > seen[eid]["score"]:
                seen[eid] = m

        all_chains: List[ReasoningChain] = []

        with self.driver.session() as session:
            for m in seen.values():
                start = ConceptNode(
                    element_id=m["element_id"],
                    name=m["node_name"],
                    type=m["node_type"],
                    matched_name=m["matched_name"],
                    matched_description=m["matched_description"],
                )

                kind = session.execute_read(
                    self._detect_concept_kind, start.element_id
                )

                if kind == "resulting_concept":
                    ci = session.execute_read(
                        self._walk_resulting_chain, start.element_id
                    )
                    if ci["final_concept"] and ci["final_paper"]:
                        all_chains.append(ReasoningChain(
                            start_concept=start,
                            steps=ci["steps"],
                            final_resulting_concept=ci["final_concept"],
                            final_paper=ci["final_paper"],
                        ))

                elif kind == "sub_concept":
                    parent_rc = session.execute_read(
                        self._find_parent_resulting_concept, start.element_id
                    )
                    if not parent_rc:
                        continue
                    ci = session.execute_read(
                        self._walk_resulting_chain, parent_rc.element_id
                    )
                    if ci["final_concept"] and ci["final_paper"]:
                        all_chains.append(ReasoningChain(
                            start_concept=start,
                            steps=ci["steps"],
                            final_resulting_concept=ci["final_concept"],
                            final_paper=ci["final_paper"],
                        ))

                else:  # other
                    chain_list = session.execute_read(
                        self._walk_from_other_concept, start.element_id
                    )
                    for ci in chain_list:
                        if ci["final_concept"] and ci["final_paper"]:
                            all_chains.append(ReasoningChain(
                                start_concept=start,
                                steps=ci["steps"],
                                final_resulting_concept=ci["final_concept"],
                                final_paper=ci["final_paper"],
                            ))

        return all_chains

    # ----------------------------------------------------------
    # Concept Kind 判斷（雲端 Cypher）
    # ----------------------------------------------------------

    @staticmethod
    def _detect_concept_kind(tx, eid: str) -> ConceptKind:
        rec = tx.run(
            """
            MATCH (c:Concept) WHERE elementId(c) = $eid
            OPTIONAL MATCH (rc:Concept {type:'Resulting_Concept'})-[:CONTAINS]->(c)
            WITH c, collect(rc) AS parents
            RETURN
              CASE
                WHEN c.type = 'Resulting_Concept' THEN 'resulting_concept'
                WHEN size(parents) > 0            THEN 'sub_concept'
                ELSE 'other'
              END AS kind
            """,
            eid=eid,
        ).single()
        return rec["kind"] if rec else "other"

    # ----------------------------------------------------------
    # 2.a  Resulting Concept 鏈條（雲端 Cypher）
    # ----------------------------------------------------------

    @staticmethod
    def _walk_resulting_chain(tx, eid: str) -> Dict[str, Any]:
        """
        RC → INSPIRES → Paper → PRODUCES → next RC → …
        只沿 INSPIRES（不含 INDIRECT_INSPIRES、APPLY_TO）走到最終 resulting_concept。
        用 visited 防止環路。
        """
        rec0 = tx.run(
            """
            MATCH (c:Concept) WHERE elementId(c) = $eid
                                AND c.type = 'Resulting_Concept'
            RETURN c, elementId(c) AS eid
            """,
            eid=eid,
        ).single()

        if not rec0:
            return {"steps": [], "final_concept": None, "final_paper": None}

        c0 = rec0["c"]
        cur = ConceptNode(
            element_id=rec0["eid"],
            name=c0.get("name"),
            type=c0.get("type"),
        )

        steps: List[ReasoningStep] = []
        last_paper: Optional[PaperNode] = None
        visited = {cur.element_id}

        while True:
            recs = tx.run(
                """
                MATCH (c:Concept) WHERE elementId(c) = $eid
                                    AND c.type = 'Resulting_Concept'
                MATCH (c)-[:INSPIRES]->(p:Paper)
                MATCH (p)-[:PRODUCES]->(next:Concept {type:'Resulting_Concept'})
                WHERE elementId(next) <> $eid
                RETURN p, next,
                       elementId(p)    AS p_eid,
                       elementId(next) AS next_eid
                """,
                eid=cur.element_id,
            ).data()

            # 從候選中取第一個尚未走訪過的 next RC
            found = None
            for rec in recs:
                if rec["next_eid"] not in visited:
                    found = rec
                    break

            if not found:
                break

            visited.add(found["next_eid"])

            p   = found["p"]
            nxt = found["next"]

            paper = PaperNode(
                element_id=found["p_eid"],
                title=p.get("title"),
                conceptual_premises=p.get("conceptual_premises"),
                contextual_model_constraints=p.get("contextual_model_constraints"),
            )
            last_paper = paper

            nxt_node = ConceptNode(
                element_id=found["next_eid"],
                name=nxt.get("name"),
                type=nxt.get("type"),
            )

            steps.append(ReasoningStep(
                from_concept=cur,
                via_paper=paper,
                to_concept=nxt_node,
            ))
            cur = nxt_node

        # Fallback：若鏈條無任何步驟，取「產出」最終 RC 的那篇 paper
        if last_paper is None:
            rec2 = tx.run(
                """
                MATCH (p:Paper)-[:PRODUCES]->(rc:Concept)
                WHERE elementId(rc) = $eid
                RETURN p, elementId(p) AS p_eid
                LIMIT 1
                """,
                eid=cur.element_id,
            ).single()
            if rec2:
                p = rec2["p"]
                last_paper = PaperNode(
                    element_id=rec2["p_eid"],
                    title=p.get("title"),
                    conceptual_premises=p.get("conceptual_premises"),
                    contextual_model_constraints=p.get("contextual_model_constraints"),
                )

        return {
            "steps": steps,
            "final_concept": cur,
            "final_paper": last_paper,
        }

    # ----------------------------------------------------------
    # 2.b  Sub-concept → 找所屬 Resulting Concept
    # ----------------------------------------------------------

    @staticmethod
    def _find_parent_resulting_concept(tx, eid: str) -> Optional[ConceptNode]:
        rec = tx.run(
            """
            MATCH (c:Concept) WHERE elementId(c) = $eid
            MATCH (rc:Concept {type:'Resulting_Concept'})-[:CONTAINS]->(c)
            RETURN rc, elementId(rc) AS rc_eid
            LIMIT 1
            """,
            eid=eid,
        ).single()
        if not rec:
            return None
        rc = rec["rc"]
        return ConceptNode(
            element_id=rec["rc_eid"],
            name=rc.get("name"),
            type=rc.get("type"),
        )

    # ----------------------------------------------------------
    # 2.c  其他 Concept → Paper → 所有 RC → 分別展開鏈條
    # ----------------------------------------------------------

    @staticmethod
    def _walk_from_other_concept(tx, eid: str) -> List[Dict[str, Any]]:
        rows = tx.run(
            """
            MATCH (c:Concept) WHERE elementId(c) = $eid
            MATCH (c)-[:INSPIRES|INDIRECT_INSPIRES|APPLY_TO]->(p:Paper)
            MATCH (p)-[:PRODUCES]->(rc:Concept {type:'Resulting_Concept'})
            RETURN DISTINCT elementId(rc) AS rc_eid
            """,
            eid=eid,
        ).data()

        chains: List[Dict[str, Any]] = []
        for row in rows:
            sub = Neo4jReasoningRetriever._walk_resulting_chain(tx, row["rc_eid"])
            chains.append(sub)
        return chains